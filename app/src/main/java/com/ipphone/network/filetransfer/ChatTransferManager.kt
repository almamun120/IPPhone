package com.ipphone.network.filetransfer

import android.content.Context
import com.ipphone.data.local.datastore.PreferencesManager
import com.ipphone.domain.model.*
import com.ipphone.domain.repository.FileTransferRepository
import com.ipphone.domain.repository.MessageRepository
import com.ipphone.network.connection.ConnectionManager
import com.ipphone.network.filetransfer.engine.FileTransferEngine
import com.ipphone.network.protocol.*
import com.ipphone.utils.FileUtils
import dagger.hilt.android.qualifiers.ApplicationContext
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.SupervisorJob
import kotlinx.coroutines.flow.filter
import kotlinx.coroutines.launch
import timber.log.Timber
import java.io.File
import javax.inject.Inject
import javax.inject.Singleton

@Singleton
class ChatTransferManager @Inject constructor(
    @ApplicationContext private val context: Context,
    private val engine: FileTransferEngine,
    private val connectionManager: ConnectionManager,
    private val fileTransferRepository: FileTransferRepository,
    private val messageRepository: MessageRepository,
    private val preferencesManager: PreferencesManager,
    private val fileTransferManagerProvider: dagger.Lazy<FileTransferManager>
) {
    private val scope = CoroutineScope(SupervisorJob() + Dispatchers.IO)

    init {
        observeEngineEvents()
        observeIncomingMessages()
    }

    private fun observeEngineEvents() {
        scope.launch {
            engine.engineEvents.collect { event ->
                when (event) {
                    is FileTransferEngine.EngineEvent.Progress -> {
                        updateProgress(event.transferId, event.fileId, event.bytesSent)
                    }
                    is FileTransferEngine.EngineEvent.FileCompleted -> {
                        finalizeFile(event.transferId, event.fileId, event.path)
                    }
                    is FileTransferEngine.EngineEvent.Error -> {
                        handleError(event.transferId, event.fileId, event.message)
                    }
                    else -> {}
                }
            }
        }
    }

    private fun observeIncomingMessages() {
        scope.launch {
            connectionManager.incomingMessages.collect { (senderId, message) ->
                if (message is FileOfferMessage && message.messageId != null) {
                    handleChatFileOffer(senderId, message)
                } else if (message is FileResponseMessage) {
                    handleChatFileResponse(senderId, message)
                }
            }
        }
    }

    /**
     * Registers an incoming chat attachment with the engine and returns the data port
     * the sender must stream to (0 when the data server could not be started).
     */
    private fun prepareIncoming(transferId: String): Int {
        engine.registerIncoming(transferId) { fileId ->
            // fileId is a UUID generated by us/the peer's app, but sanitise anyway.
            val dir = FileUtils.getInternalReceivedDirectory(context)
            FileUtils.createUniqueFileNamed(dir, fileId).absolutePath
        }
        return engine.ensureDataServer()
    }

    fun enqueueTransfer(transfer: FileTransfer) {
        if (transfer.totalSize > 100 * 1024 * 1024) { // 100 MB limit
            scope.launch {
                fileTransferRepository.markAsFailed(transfer.id, "File size exceeds 100 MB limit for chat")
            }
            return
        }

        scope.launch {
            fileTransferRepository.saveTransfer(transfer)
            fileTransferRepository.updateStatus(transfer.id, TransferStatus.WAITING_ACCEPTANCE)

            val offer = FileOfferMessage(
                senderId = preferencesManager.getDeviceUuid(),
                transferId = transfer.id,
                messageId = transfer.messageId,
                files = transfer.files.map { it.toMetadata() },
                totalSize = transfer.totalSize
            )

            if (!connectionManager.sendMessage(transfer.peerId, offer)) {
                fileTransferRepository.markAsFailed(transfer.id, "Failed to send offer")
            }
        }
    }

    suspend fun acceptTransfer(transferId: String) {
        val transfer = fileTransferRepository.getTransferByIdOnce(transferId) ?: return
        val response = FileResponseMessage(
            senderId = preferencesManager.getDeviceUuid(),
            transferId = transferId,
            accepted = true,
            dataPort = prepareIncoming(transferId)
        )
        fileTransferRepository.markAsStarted(transferId, TransferStatus.ACTIVE)
        connectionManager.sendMessage(transfer.peerId, response)
    }

    fun getContext(): Context = context

    private suspend fun handleChatFileOffer(senderId: String, offer: FileOfferMessage) {
        if (offer.totalSize > 100 * 1024 * 1024) {
            val response = FileResponseMessage(
                senderId = preferencesManager.getDeviceUuid(),
                transferId = offer.transferId,
                accepted = false,
                reason = "File size exceeds 100 MB limit for chat"
            )
            connectionManager.sendMessage(senderId, response)
            return
        }

        val transfer = FileTransfer(
            id = offer.transferId,
            messageId = offer.messageId,
            peerId = senderId,
            direction = TransferDirection.INCOMING,
            status = TransferStatus.WAITING_ACCEPTANCE, // Start as waiting, then auto-accept if it's a chat file
            totalSize = offer.totalSize,
            fileCount = offer.files.size,
            files = offer.files.mapIndexed { index, meta -> meta.toDomain(offer.transferId, index) }
        )

        fileTransferRepository.saveTransfer(transfer)
        
        // For Chat Messages, we auto-accept immediately to start the transfer
        fileTransferRepository.markAsStarted(offer.transferId, TransferStatus.ACTIVE)
        val response = FileResponseMessage(
            senderId = preferencesManager.getDeviceUuid(),
            transferId = offer.transferId,
            accepted = true,
            dataPort = prepareIncoming(offer.transferId)
        )
        connectionManager.sendMessage(senderId, response)
    }

    private suspend fun handleChatFileResponse(senderId: String, response: FileResponseMessage) {
        val transfer = fileTransferRepository.getTransferByIdOnce(response.transferId) ?: return
        if (transfer.messageId == null) return

        if (response.accepted) {
            engine.setPeerDataPort(transfer.id, response.dataPort)
            fileTransferRepository.markAsStarted(transfer.id, TransferStatus.ACTIVE)
            transfer.files.forEach { file ->
                engine.sendFile(senderId, transfer.id, file.id, file.filePath, file.fileSize)
            }
        } else {
            fileTransferRepository.markAsFailed(transfer.id, response.reason ?: "Rejected")
        }
    }

    suspend fun rejectTransfer(transferId: String, reason: String? = null) {
        val transfer = fileTransferRepository.getTransferByIdOnce(transferId) ?: return
        val response = FileResponseMessage(
            senderId = preferencesManager.getDeviceUuid(),
            transferId = transferId,
            accepted = false,
            reason = reason
        )
        fileTransferRepository.markAsFailed(transferId, reason ?: "Rejected by user")
        connectionManager.sendMessage(transfer.peerId, response)
    }

    private suspend fun updateProgress(transferId: String, fileId: String, bytesSent: Long) {
        fileTransferRepository.updateFileProgress(fileId, bytesSent, TransferFileStatus.ACTIVE.name)
        // Optionally update total transfer progress
    }

    private suspend fun finalizeFile(transferId: String, fileId: String, path: String) {
        val transfer = fileTransferRepository.getTransferByIdOnce(transferId) ?: return
        if (transfer.messageId == null) return

        fileTransferRepository.updateFileProgress(fileId, -1, TransferFileStatus.COMPLETED.name)
        fileTransferRepository.updateFilePath(fileId, path)
        
        messageRepository.updateMediaPath(transfer.messageId, path)
        messageRepository.updateStatus(transfer.messageId, MessageStatus.DELIVERED)

        val allDone = transfer.files.all { it.id == fileId || it.status == TransferFileStatus.COMPLETED }
        if (allDone) {
            fileTransferRepository.markAsCompleted(transferId)
            engine.releaseTransfer(transferId)
            if (transfer.direction == TransferDirection.INCOMING) {
                scope.launch {
                    fileTransferManagerProvider.get().saveTransferToDownloads(transferId)
                }
            }
        }
    }

    private suspend fun handleError(transferId: String, fileId: String?, message: String) {
        val transfer = fileTransferRepository.getTransferByIdOnce(transferId) ?: return
        if (transfer.messageId == null) return
        fileTransferRepository.markAsFailed(transferId, message)
    }

    private fun FileMetadata.toDomain(transferId: String, index: Int) = TransferFile(
        id = id,
        transferId = transferId,
        fileName = name,
        filePath = "",
        relativePath = relativePath,
        fileSize = size,
        mimeType = mimeType,
        isDirectory = isDirectory,
        checksum = checksum,
        indexOrder = index
    )

    private fun TransferFile.toMetadata() = FileMetadata(
        id = id,
        name = fileName,
        relativePath = relativePath,
        size = fileSize,
        mimeType = mimeType,
        isDirectory = isDirectory,
        checksum = checksum
    )
}

